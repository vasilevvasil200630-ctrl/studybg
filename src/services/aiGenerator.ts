import type { LessonData, Flashcard, QuizQuestion } from '../types';

export function generateLessonFromInput(
  titleOrFileName: string,
  rawText: string,
  subjectHint = 'Общообразователен предмет'
): LessonData {
  const cleanTitle = titleOrFileName
    .replace(/\.(jpg|jpeg|png|heic|pdf|txt)$/i, '')
    .replace(/[-_]/g, ' ')
    .trim() || 'Сканиран урок от тетрадка';

  // Extract lines and sentences
  const lines = rawText.split('\n').map(l => l.trim()).filter(l => l.length > 0);

  // Generate overview
  const overview = rawText.length > 60
    ? `Синтезиран преглед от сканираните записки: ${rawText.slice(0, 220)}... Този урок обхваща ключови понятия, процеси и взаимовръзки, съобразени с българската учебна програма.`
    : `Този урок по ${subjectHint} съдържа най-важните акценти и структурирани знания от вашата тетрадка. Подготвен е за светкавичен 5-минутен преговор преди контролна работа или изпит.`;

  // Generate key points
  const keyPoints: string[] = [];
  if (lines.length >= 3) {
    lines.slice(0, 5).forEach((line, idx) => {
      keyPoints.push(`Точка ${idx + 1}: ${line.length > 120 ? line.slice(0, 120) + '...' : line}`);
    });
  } else {
    keyPoints.push(
      `Основни дефиниции и понятиен апарат: Вникнете в причинно-следствените връзки на темата.`,
      `Главни процеси и механизми: Проследете последователността на събитията стъпка по стъпка.`,
      `Приложение и практически примери: Свържете теорията с реални задачи и матурни формати.`,
      `Обобщение и изводи: Формулирайте най-важните заключения със свои думи.`
    );
  }

  // Generate flashcards
  const flashcards: Flashcard[] = [
    {
      id: `fc-gen-1`,
      front: `Какво е главното послание или дефиниция в „${cleanTitle}“?`,
      back: keyPoints[0] || 'Основната същност на концепцията, записана в началото на темата.',
      hint: 'Погледни първите 2 реда от записките си.',
      tag: 'Основна концепция'
    },
    {
      id: `fc-gen-2`,
      front: `Кой е най-важният процес или събитие, разгледано в този урок?`,
      back: keyPoints[1] || 'Централният механизъм или повратна точка в учебния материал.',
      hint: 'Свързано е с динамиката на темата.',
      tag: 'Ключов процес'
    },
    {
      id: `fc-gen-3`,
      front: `Каква е формулата / логическото правило, което не бива да се бърка?`,
      back: 'Всяко правило изисква внимание към изключенията и правилната терминология.',
      hint: 'Често се появява на второ ниво в тестовете.',
      tag: 'Правило'
    },
    {
      id: `fc-gen-4`,
      front: `Какъв е крайният резултат или извод от разгледаната тема?`,
      back: keyPoints[keyPoints.length - 1] || 'Крайното състояние или исторически/научен извод.',
      hint: 'Търси заключителния абзац.',
      tag: 'Извод'
    },
    {
      id: `fc-gen-5`,
      front: `Коя е най-честата грешка, която учениците допускат по тази тема?`,
      back: 'Смесване на сродни понятия или неточно цитиране на дати, формули и зависимости.',
      hint: 'Обърни внимание на знаците и мерните единици.',
      tag: 'Клопка'
    }
  ];

  // Generate 10 Quiz questions
  const quiz: QuizQuestion[] = [
    {
      id: 1,
      question: `Кое е основното понятие, заложено в основата на „${cleanTitle}“?`,
      options: [
        `Ключовата теза: ${keyPoints[0]?.slice(0, 45) || 'Базовият принцип на урока'}`,
        'Вторично и несъществено отклонение от темата',
        'Остаряла концепция, която днес не се изучава',
        'Елемент, нямащ връзка с българския учебен план'
      ],
      correctIndex: 0,
      explanation: 'Това е водещото твърдение, от което произтичат всички останали изводи в урока.'
    },
    {
      id: 2,
      question: `По какъв начин най-точно се класифицира съдържанието на този урок?`,
      options: [
        'Като абстрактна хипотеза без доказателства',
        'Като задължително учебно ядро съгласно стандартите на МОН',
        'Като препоръчителна факултативна литература',
        'Като въпрос единствено за олимпиади по специалността'
      ],
      correctIndex: 1,
      explanation: 'Материалът е част от държавните образователни изисквания за съответния клас.'
    },
    {
      id: 3,
      question: `Каква е логическата връзка между отделните етапи в темата?`,
      options: [
        'Етапите са напълно произволни и независими един от друг',
        'Всеки следващ етап надгражда и доказва предходния',
        'Има противоречие между първата и втората част',
        'Липсва всякаква хронологична или логическа последователност'
      ],
      correctIndex: 1,
      explanation: 'Причинно-следствената връзка е ключът към пълна оценка 6.00.'
    },
    {
      id: 4,
      question: `Кое от изброените твърдения представлява „капан“ (честа грешка) за учениците?`,
      options: [
        'Точното спазване на научната терминология',
        'Смесването на основните признаци с второстепенни характеристики',
        'Внимателното четене на условията на въпросите',
        'Преговорът с кратки структурирани флашкарти'
      ],
      correctIndex: 1,
      explanation: 'Учителите често задават подвеждащи въпроси, разчитащи на повърхностно запомняне.'
    },
    {
      id: 5,
      question: `Какъв метод на подготовка препоръчва StudyBG за максимално усвояване?`,
      options: [
        'Зубрене на изуст цяла нощ преди контролното',
        'Светата троица: 1/2 страница Резюме + Флашкарти + Тест за 5 минути',
        'Преписване на целия учебник дума по дума',
        'Игнориране на темата до края на срока'
      ],
      correctIndex: 1,
      explanation: 'Светата троица ангажира активното припомняне (Active Recall) и интервалното повторение.'
    },
    {
      id: 6,
      question: `Какво е значението на практическото приложение на материала?`,
      options: [
        'Показва реалния смисъл на знанието отвъд сухата теория',
        'Няма никакво практическо значение',
        'Служи само за усложняване на изпита',
        'Използва се само в научни лаборатории'
      ],
      correctIndex: 0,
      explanation: 'Разбирането на приложението прави материала лесен за запомняне.'
    },
    {
      id: 7,
      question: `Кой е най-бързият начин да проверите дали помните детайлите?`,
      options: [
        'Да затворите тетрадката и да завъртите флашкартите',
        'Да чакате съученик да ви подскаже в час',
        'Да се надявате темата да бъде пропусната',
        'Да прочетете заглавието още 10 пъти'
      ],
      correctIndex: 0,
      explanation: 'Флашкартите тестват паметта без възможност за самозаблуда.'
    },
    {
      id: 8,
      question: `Каква роля играе AI асистентът „Питай тетрадката си“?`,
      options: [
        'Пише домашни вместо ученика без мислене',
        'Обяснява сложни пасажи по разбираем начин и цитира записките',
        'Замества напълно живия учител',
        'Служи единствено за забавление в свободното време'
      ],
      correctIndex: 1,
      explanation: 'AI асистентът изяснява двусмислици и отговаря на конкретни въпроси от листа.'
    },
    {
      id: 9,
      question: `Кой от следните източници носи най-висок резултат при преговор?`,
      options: [
        'Синтезирано резюме със схеми и ключови думи',
        'Нечетими чернови без ред и структура',
        'Случайни бележки от социалните мрежи',
        'Непроверени форумни коментари'
      ],
      correctIndex: 0,
      explanation: 'Структурираното половинстранично резюме дава бърз цялостен поглед.'
    },
    {
      id: 10,
      question: `Ако имате 10 верни отговора на този тест, каква е вашата готовност?`,
      options: [
        'Слаба подготовка, имате нужда от пълен преговор',
        'Отличен 6.00 — напълно готови за контролно или изпит! 🏆',
        'Среден резултат с много пропуски',
        'Неопределено състояние без ясна оценка'
      ],
      correctIndex: 1,
      explanation: 'Поздравления! 10 от 10 верни отговора съответства на пълен Отличен (6.00) по българската система.'
    }
  ];

  return {
    id: `custom-lesson-${Date.now()}`,
    title: cleanTitle,
    subject: subjectHint,
    grade: 'Учебен материал',
    sourceType: 'notebook',
    originalNoteExcerpt: rawText.slice(0, 300) || 'Сканиран ръкопис от тетрадка',
    summary: {
      overview,
      keyPoints,
      examGoldenRule: `Внимавай в детайлите на „${cleanTitle}“: Учителите изискват точни дефиниции и ясна връзка между причини и следствия!`,
      commonTraps: [
        'Смесване на основни понятия с второстепенни термини.',
        'Пропускане на изключенията от общото правило при тестовите въпроси.'
      ],
      formulasOrDates: [
        { label: 'Ключов акцент', value: cleanTitle },
        { label: 'Стандарт', value: 'МОН 2026/2027' },
        { label: 'Формат', value: 'Светата троица (5 мин)' }
      ]
    },
    flashcards,
    quiz,
    quickQuestions: [
      `Обясни ми „${cleanTitle}“ като на приятел 💬`,
      'Кой въпрос най-вероятно ще даде учителят? 🎯',
      'Дай ми кратък пример от практиката 💡',
      'Как да запомня формулата/правилото за 2 минути? 🧠'
    ]
  };
}
