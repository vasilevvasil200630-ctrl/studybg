export interface CurriculumSubDomain {
  id: string;
  name: string; // Име на темата / под-дяла
  keywords: string[]; // Думи за разпознаване на почерка
  gradeRequirement6: string[]; // Какво задължително изискват учителите за 6.00
  commonPitfalls: string[]; // Чести грешки
  advice: string; // Персонален съвет за подготовка
}

export interface CurriculumDomain {
  id: string;
  name: string; // Име на дяла (напр. Дял III: Българското възраждане)
  subDomains: CurriculumSubDomain[];
}

