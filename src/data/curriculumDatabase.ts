let cachedFullCurriculum: LessonData[] | null = null;
let inflightCurriculumPromise: Promise<LessonData[]> | null = null;

export function getCachedOrCoreLessons(): LessonData[] {
  return cachedFullCurriculum || CURRICULUM_LESSONS;
}

export async function loadFullCurriculumLessons(): Promise<LessonData[]> {
  if (cachedFullCurriculum) {
    return cachedFullCurriculum;
  }
  if (inflightCurriculumPromise) {
    return inflightCurriculumPromise;
  }
  inflightCurriculumPromise = Promise.all([
    import('./curriculumCorePack'),
    import('./curriculumExpansionLessons'),
    import('./curriculumExpansionLessonsPart1B'),
    import('./curriculumExpansionLessonsPart2'),
    import('./curriculumExpansionLessonsPart3'),
    import('./monLessons')
  ]).then(([corePack, part1A, part1B, part2, part3, monLessons]) => {
    const fullRaw: LessonData[] = [
      ...monLessons.MON_LESSONS,
      ...part1A.EXTRA_CURRICULUM_LESSONS,
      ...part1B.EXTRA_CURRICULUM_LESSONS_PART1B,
      ...part2.EXTRA_CURRICULUM_LESSONS_PART2,
      ...part3.EXTRA_CURRICULUM_LESSONS_PART3,
      ...CORE_CURRICULUM_LESSONS,
      ...corePack.CORE_CURRICULUM_PACK
    ].map(ensureNotebookChecklist);
    cachedFullCurriculum = buildInterleavedCurriculum(fullRaw);
    return cachedFullCurriculum;
  }).catch((err: unknown) => {
    // Не кешираме неуспеха — следващото извикване опитва отново (напр. след връщане онлайн)
    inflightCurriculumPromise = null;
    throw err;
  });
  return inflightCurriculumPromise;
}


